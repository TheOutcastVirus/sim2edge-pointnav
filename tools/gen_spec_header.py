#!/usr/bin/env python3
"""Transcribe ``sim2edge/spec.py`` into a C++ header for the board.

The rule this script exists to enforce: **there is exactly one source of truth
for the observation contract, and it is the Python file.** The board's C++ must
agree with it bit for bit or the policy is fed inputs it was never calibrated
on -- which does not crash and does not log, it just drives into a wall.

Two protections come out of this:

1. Every constant is *imported* from ``sim2edge.spec`` rather than retyped, so a
   change there cannot silently fail to reach C++. Re-running this script is the
   whole update procedure.
2. The generated header carries ``kObservationFingerprint``. The policy node
   compares it against the fingerprint recorded beside the ``.pte`` at load and
   refuses to run on a mismatch. A quantized graph built under a different
   preprocessing contract produces plausible-looking garbage, never an error, so
   that check is load-bearing.

Regenerate with::

    .venv/bin/python tools/gen_spec_header.py

and commit the result. It is checked into git deliberately: the board has no
network and no Python project environment, so it cannot generate this itself.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from sim2edge import spec  # noqa: E402

DEFAULT_OUT = (REPO / "ros2_ws/src/sim2edge_core/include/sim2edge"
               / "spec_generated.hpp")

TEMPLATE = '''\
// AUTO-GENERATED by tools/gen_spec_header.py -- DO NOT EDIT.
//
// Source of truth: sim2edge/spec.py. Regenerate with
//     .venv/bin/python tools/gen_spec_header.py
// and commit the result; the board has no Python environment to build it from.
//
// kObservationFingerprint is compared against the fingerprint recorded beside
// the .pte at model load. A graph quantized under a different preprocessing
// contract returns plausible-looking garbage rather than an error, so that
// comparison is the only thing standing between a contract change and a silent
// sim-to-real gap. Do not remove it.

#pragma once

#include <cstddef>

namespace sim2edge::spec
{{

// ── Contract identity ────────────────────────────────────────────────────────
inline constexpr const char * kSensorContractVersion = "{sensor_contract_version}";
inline constexpr const char * kMotionPriorSource = "{motion_prior_source}";
inline constexpr const char * kRawFingerprint = "{raw_fingerprint}";
inline constexpr const char * kSensorModelFingerprint = "{sensor_model_fingerprint}";
inline constexpr const char * kObservationFingerprint = "{observation_fingerprint}";

// ── Lidar ────────────────────────────────────────────────────────────────────
// 180 bins over the full circle. Full circle rather than a forward arc because
// backing out of a dead end requires seeing behind.
inline constexpr int kLidarBins = {lidar_bins};
inline constexpr float kLidarMinM = {lidar_min_m}f;
inline constexpr float kLidarMaxM = {lidar_max_m}f;
// What an absent return normalizes to. 1.0 == "nothing out to max range".
// NOT 0.0 -- zero denormalizes to kLidarMinM, i.e. an obstacle 15 cm dead
// ahead filling every bin, which stops the robot permanently.
inline constexpr float kInvalidFill = {invalid_fill}f;
inline constexpr float kBinWidthRad = {bin_width_rad}f;

// ── Spinning sensor ──────────────────────────────────────────────────────────
// The A1 is a motor at ~5.5 Hz: one revolution spans 3.6 control periods, so a
// "scan" is stitched from beams acquired at three or four different poses.
inline constexpr float kLidarSpinHz = {lidar_spin_hz}f;
inline constexpr float kSpinPeriodS = {spin_period_s}f;
inline constexpr int kSpinTicks = {spin_ticks};
inline constexpr bool kDeskewWithGyro = {deskew_with_gyro};
inline constexpr int kMotionHistoryFrames = {motion_history_frames};

// ── Goal ─────────────────────────────────────────────────────────────────────
inline constexpr float kGoalMaxM = {goal_max_m}f;
inline constexpr float kGoalToleranceM = {goal_tolerance_m}f;
inline constexpr int kGoalDim = 3;

// ── Action: physical (v, omega), the units the Twist carries ─────────────────
inline constexpr float kVMax = {v_max}f;
inline constexpr float kOmegaMax = {omega_max}f;
inline constexpr float kAccelMax = {accel_max}f;
inline constexpr float kAlphaMax = {alpha_max}f;
inline constexpr float kDt = {dt}f;
inline constexpr float kControlHz = {control_hz}f;
inline constexpr int kActionDim = 2;

// ── Robot ────────────────────────────────────────────────────────────────────
inline constexpr float kRobotRadiusM = {robot_radius_m}f;   // planning inflation
inline constexpr float kBodyRadiusM = {body_radius_m}f;     // actual contact radius
inline constexpr float kLidarMountX = {lidar_mount_x}f;
inline constexpr float kLidarMountY = {lidar_mount_y}f;
inline constexpr float kLidarMountZ = {lidar_mount_z}f;
// The sensor is bolted on rotated a quarter turn: beam bearings arrive 90
// degrees off the robot's forward axis and MUST be rotated into base_link
// before binning. The goal bearing is in the robot frame, so a scan left in the
// lidar frame puts every obstacle at right angles to where the policy thinks it
// is.
inline constexpr float kLidarMountYaw = {lidar_mount_yaw}f;

// ── Observation layout ───────────────────────────────────────────────────────
// Flat, oldest-to-newest within each history block:
//     [ lidar(H, B) | goal(3) | previous_action(H, 2) ]
inline constexpr int kHistoryFrames = {history_frames};
inline constexpr int kObsDim = {obs_dim};
inline constexpr std::size_t kLidarBlock = static_cast<std::size_t>(kHistoryFrames) * kLidarBins;
inline constexpr std::size_t kGoalOffset = kLidarBlock;
inline constexpr std::size_t kActionOffset = kLidarBlock + kGoalDim;

static_assert(kObsDim == static_cast<int>(kActionOffset) + kHistoryFrames * kActionDim,
              "observation layout disagrees with kObsDim");

}}  // namespace sim2edge::spec
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true",
                        help="exit non-zero if the file on disk is stale, "
                             "instead of rewriting it")
    args = parser.parse_args()

    text = TEMPLATE.format(
        sensor_contract_version=spec.SENSOR_CONTRACT_VERSION,
        motion_prior_source=spec.MOTION_PRIOR_SOURCE,
        raw_fingerprint=spec.fingerprint(),
        sensor_model_fingerprint=spec.sensor_model_fingerprint(),
        observation_fingerprint=spec.observation_fingerprint(),
        lidar_bins=spec.LIDAR_BINS,
        lidar_min_m=repr(spec.LIDAR_MIN_M),
        lidar_max_m=repr(spec.LIDAR_MAX_M),
        invalid_fill=repr(float(spec.INVALID_FILL)),
        bin_width_rad=repr(spec.BIN_WIDTH_RAD),
        lidar_spin_hz=repr(spec.LIDAR_SPIN_HZ),
        spin_period_s=repr(1.0 / spec.LIDAR_SPIN_HZ),
        spin_ticks=spec.SPIN_TICKS,
        deskew_with_gyro="true" if spec.DESKEW_WITH_GYRO else "false",
        motion_history_frames=spec.MOTION_HISTORY_FRAMES,
        goal_max_m=repr(spec.GOAL_MAX_M),
        goal_tolerance_m=repr(spec.GOAL_TOLERANCE_M),
        v_max=repr(spec.V_MAX),
        omega_max=repr(spec.OMEGA_MAX),
        accel_max=repr(spec.ACCEL_MAX),
        alpha_max=repr(spec.ALPHA_MAX),
        dt=repr(spec.DT),
        control_hz=repr(1.0 / spec.DT),
        robot_radius_m=repr(spec.ROBOT_RADIUS_M),
        body_radius_m=repr(spec.BODY_RADIUS_M),
        lidar_mount_x=repr(spec.LIDAR_MOUNT_XYZ[0]),
        lidar_mount_y=repr(spec.LIDAR_MOUNT_XYZ[1]),
        lidar_mount_z=repr(spec.LIDAR_MOUNT_XYZ[2]),
        lidar_mount_yaw=repr(spec.LIDAR_MOUNT_YAW),
        history_frames=spec.HISTORY_FRAMES,
        obs_dim=spec.OBS_DIM,
    )

    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        if current != text:
            print(f"stale: {args.out} does not match sim2edge/spec.py",
                  file=sys.stderr)
            return 1
        print(f"up to date: {args.out}")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f"wrote {args.out}")
    print(f"  observation fingerprint {spec.observation_fingerprint()}")
    print(f"  sensor contract         {spec.SENSOR_CONTRACT_VERSION}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
