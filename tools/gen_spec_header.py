#!/usr/bin/env python3
"""Generate the C++ spec header (and spec.json) from ``sim2edge/spec.py``.

The C++ node must not carry its own copy of the preprocessing constants. Every
constant it needs is emitted here from the one Python definition, so a change to
the contract cannot be applied to training and forgotten on the robot — the
worst version of the calibration/runtime mismatch that bit both reference
projects, because it fails silently rather than loudly.

Run after any change to ``sim2edge/spec.py`` and commit the result:

    python3 tools/gen_spec_header.py

CI (``tests/test_spec_header_current.py``) fails if the committed header is
stale, so this cannot be skipped by accident.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from sim2edge.spec import DEFAULT_SPEC, NavSpec  # noqa: E402

REPO = pathlib.Path(__file__).resolve().parents[1]
DEFAULT_HEADER = (REPO / "ros_ws/src/nav_policy_node/include/nav_policy_node/"
                  "spec_generated.hpp")
DEFAULT_JSON = REPO / "configs/spec.json"


def render_header(spec: NavSpec) -> str:
    d, l = spec.obs.depth, spec.obs.lidar
    g, a = spec.obs.goal, spec.action
    s, r = spec.safety, spec.robot

    inputs = ", ".join(f'"{name}"' for name in spec.obs.actor_inputs)

    return f"""// AUTO-GENERATED by tools/gen_spec_header.py -- DO NOT EDIT.
//
// Source of truth: sim2edge/spec.py (spec version {spec.version}).
// Regenerate with:  python3 tools/gen_spec_header.py
//
// The runtime checks kSpecFingerprint against the fingerprint recorded in the
// .pte sidecar at model load. A policy quantized under a different
// preprocessing contract produces plausible-looking garbage rather than an
// error, so that check is load-bearing -- do not remove it.

#pragma once

#include <array>
#include <cstddef>

namespace nav_policy_node {{
namespace spec {{

inline constexpr const char * kSpecVersion = "{spec.version}";
inline constexpr const char * kSpecFingerprint = "{spec.fingerprint()}";

// ── Actor input order (positional order of the exported graph's inputs) ──────
inline constexpr std::array<const char *, {len(spec.obs.actor_inputs)}>
  kActorInputs = {{{inputs}}};

// ── Depth ───────────────────────────────────────────────────────────────────
inline constexpr int kDepthHeight = {d.height};
inline constexpr int kDepthWidth = {d.width};
inline constexpr float kDepthMinM = {d.min_m}f;
inline constexpr float kDepthMaxM = {d.max_m}f;
inline constexpr float kDepthInvalidFill = {d.invalid_fill}f;
inline constexpr float kDepthRawScaleToM = {d.raw_scale_to_m}f;
inline constexpr std::size_t kDepthNumel = {d.numel};

// ── Lidar ───────────────────────────────────────────────────────────────────
inline constexpr int kLidarBins = {l.bins};
inline constexpr float kLidarMinM = {l.min_m}f;
inline constexpr float kLidarMaxM = {l.max_m}f;
inline constexpr float kLidarInvalidFill = {l.invalid_fill}f;
inline constexpr float kLidarAngleMin = {l.angle_min}f;
inline constexpr float kLidarAngleMax = {l.angle_max}f;

// ── Goal ────────────────────────────────────────────────────────────────────
inline constexpr float kGoalMaxDistanceM = {g.max_distance_m}f;
inline constexpr int kGoalDim = 3;

// ── Action ──────────────────────────────────────────────────────────────────
inline constexpr int kActionDim = 2;
inline constexpr float kVMax = {a.v_max}f;
inline constexpr float kVMin = {a.v_min}f;
inline constexpr float kOmegaMax = {a.omega_max}f;
inline constexpr float kAccelMax = {a.accel_max}f;
inline constexpr float kAlphaMax = {a.alpha_max}f;
inline constexpr float kControlRateHz = {a.control_rate_hz}f;
inline constexpr float kControlDt = {a.dt}f;

// ── Safety layer ────────────────────────────────────────────────────────────
inline constexpr float kForwardSectorRad = {s.forward_sector_rad}f;
inline constexpr float kStopDistanceM = {s.stop_distance_m}f;
inline constexpr float kSlowDistanceM = {s.slow_distance_m}f;
inline constexpr float kPolicyTimeoutS = {s.policy_timeout_s}f;
inline constexpr float kLidarMaxAgeS = {s.lidar_max_age_s}f;
inline constexpr float kDepthMaxAgeS = {s.depth_max_age_s}f;
inline constexpr float kOdomMaxAgeS = {s.odom_max_age_s}f;

// ── Robot geometry ──────────────────────────────────────────────────────────
inline constexpr float kRobotRadiusM = {r.radius_m}f;

}}  // namespace spec
}}  // namespace nav_policy_node
"""


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--header", type=pathlib.Path, default=DEFAULT_HEADER)
    p.add_argument("--json", type=pathlib.Path, default=DEFAULT_JSON)
    p.add_argument("--check", action="store_true",
                   help="Exit non-zero if the committed files are stale "
                        "instead of rewriting them.")
    args = p.parse_args()

    header_text = render_header(DEFAULT_SPEC)
    json_text = DEFAULT_SPEC.to_json() + "\n"

    if args.check:
        stale = []
        for path, want in ((args.header, header_text), (args.json, json_text)):
            if not path.exists() or path.read_text() != want:
                stale.append(str(path.relative_to(REPO)))
        if stale:
            print("Stale generated files: " + ", ".join(stale), file=sys.stderr)
            print("Run: python3 tools/gen_spec_header.py", file=sys.stderr)
            return 1
        print("Generated files are up to date.")
        return 0

    for path, text in ((args.header, header_text), (args.json, json_text)):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"Wrote {path.relative_to(REPO)}")
    print(f"Spec fingerprint: {DEFAULT_SPEC.fingerprint()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
